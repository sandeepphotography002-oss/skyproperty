<h2>Why the shape of the ground decides it</h2>

<p>Water collects at the bottom. To see a lake you have to be above it with nothing in between — a ridge, a shoulder of hill, or tall trees will hide water that is only a few hundred metres away.</p>

<ul>
  <li><strong>Slopes facing into the bowl</strong> can see the water, depending on height and what is in the way.</li>
