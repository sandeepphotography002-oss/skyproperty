<p>The commonest question after "how much is the plot" is "what will it cost to build". People expect a rate per square foot. In the hills that number is close to meaningless, and here is why.</p>

<p>On flat ground, two identical houses cost roughly the same. On a slope they do not, because before you build the house you have to build the ground it stands on. That work is invisible in the finished photograph and it is where hill budgets go.</p>

<h2>Where the extra money goes</h2>

<h3>Retaining walls and cutting</h3>
<p>This is the big one. A gentle slope may need a single retaining wall. A steep cut can need three, plus deeper foundations on the lower side. Two plots of the same size, one gentle and one steep, can differ by lakhs before a single wall of the house goes up.</p>

<p>When you look at a plot, look at the slope and ask a contractor what it will take to make a level platform. That is the real first line of your budget.</p>

<h3>Getting material to the site</h3>
<p>Sand, cement, steel, stone, tiles — all of it has to arrive. If a tractor or small truck reaches the plot, you pay normal transport. If the last stretch is a footpath, everything comes by head-load, and the same house costs substantially more.</p>

<p>This is the reason we keep going on about approach roads. It is not about your convenience on a Sunday. It is about what you will pay to build and what the plot is worth later.</p>

<h3>Water for construction</h3>
<p>Building needs a lot of water over several months. On a plot with only a seasonal channel that means tankers, month after month, on a narrow road. Ask where the construction water will come from before you buy, not after.</p>

<h3>Labour</h3>
<p>Crews travel up from below. That affects both the rate and the pace, and it means a site that is hard to reach is also a site that is slow.</p>

<h3>The monsoon</h3>
<p>Work stops, or nearly does, from about July to September. Plan for the shell to be up before then, or accept a gap of two to three months in the middle of your build.</p>

