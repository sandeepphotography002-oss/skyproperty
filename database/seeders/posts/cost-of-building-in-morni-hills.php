<h2>Getting approvals</h2>

<p>Before any of the above matters, the land has to allow a house at all.</p>

<ul>
  <li><strong>Residential-classified land</strong> — the ordinary approvals apply, through the relevant local authority. Straightforward if the papers are clean.</li>
  <li><strong>Agricultural land</strong> — a change of land use is needed first. It is an application, not a right; it costs money, takes months, and can be refused.</li>
</ul>

<p>Treat a CLU as a "no" when you price the plot. If it comes through, you have gained. If you buy assuming it will, you may end up with land you cannot use and cannot easily sell, because the next buyer will run the same sums you should have.</p>

<h2>Mistakes that cost the most</h2>

<ul>
  <li><strong>Budgeting from a per-square-foot rate.</strong> It ignores the platform, which on a slope is the largest single item.</li>
  <li><strong>Starting in April.</strong> The shell will not be up before the rain, and you will lose the season.</li>
  <li><strong>Using a plains contractor.</strong> Slope, drainage and access are learned locally, and the first monsoon is an expensive way to teach someone.</li>
  <li><strong>Skimping on drainage.</strong> It is invisible, it is cheap at the time, and it causes more hill-house damage than anything else.</li>
  <li><strong>Building to the edge of the budget.</strong> Sites reveal things once cutting starts. A build that stalls at plaster is a common sight here and a miserable position to be in.</li>
  <li><strong>Not being there.</strong> A fortnightly visit is not supervision. Either move nearby for the duration or pay someone to watch it daily.</li>
</ul>

<h2>A sensible order of spending</h2>

<ol>
  <li>Survey and levels — know the ground before designing for it</li>
  <li>Cutting and retaining — priced separately, and first</li>
  <li>Foundation and structure — aimed to finish before July</li>
  <li>Roof and waterproofing — never the place to save</li>
  <li>Drainage — planned, not improvised</li>
  <li>Water storage and connections</li>
  <li>Finishing — last, and where you can slow down if money gets tight</li>
</ol>

<p>Ordering it this way means that if you do run short, you stop at an unfinished interior in a weathertight house. Do it the other way round and you stop with beautiful tiles under a roof that leaks.</p>

