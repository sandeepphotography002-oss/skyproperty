<h2>How long it takes</h2>

<p>Longer than the plains. Between the monsoon gap, crews travelling up, and material arriving in smaller loads, a build that would take eight months below can take a year or more here.</p>

<p>Plan the timeline around the rain rather than around a target date. Anyone promising you a fast build in the hills has either not built here or is not telling you about the monsoon.</p>

