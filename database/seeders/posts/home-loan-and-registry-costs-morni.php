<h3>What a bank will look at</h3>

<ul>
  <li>Clean title, mutation entered, no encumbrance</li>
  <li>Land use classification &mdash; residential is far easier</li>
  <li>Approach road and whether the property can be valued and resold</li>
  <li>Their own valuation, which may come in below your agreed price</li>
  <li>Your income and existing obligations, as with any loan</li>
</ul>

<h3>What to do about it</h3>

<p><strong>Talk to your bank before you commit, not after.</strong> Take the khasra number and the jamabandi to them and ask whether they would lend on it in principle. Ten minutes there can save an agreement you cannot complete.</p>

<p>And understand the gap: if the bank values the plot below the price, the difference comes from you, on top of your deposit.</p>

<h2>The costs people forget</h2>

<ul>
  <li><strong>Mutation follow-up.</strong> Small in money, and the step most often left undone.</li>
  <li><strong>Fencing.</strong> Worth doing early on empty land, particularly if you are not local.</li>
  <li><strong>The electricity connection.</strong> Priced on the distance to the nearest pole, which is why that distance is worth asking about at the viewing.</li>
  <li><strong>A borewell,</strong> if there is no line. Depth is unknown until it is drilled.</li>
  <li><strong>Retaining walls,</strong> if you build. On a slope this is the largest hidden item of the whole project.</li>
  <li><strong>Travel.</strong> Two hours each way, many times, through the buying process and then for years.</li>
