<h2>A sensible way to budget</h2>

<ol>
  <li>Decide the total you are willing to spend, all in</li>
  <li>Take off stamp duty and registration &mdash; get the real figure from the tehsil</li>
  <li>Take off the advocate, record copies and brokerage</li>
  <li>Take off fencing and a connection if the plot is bare</li>
  <li>What is left is your actual plot budget</li>
</ol>

<p>Most buyers do this in the wrong order, spend the whole amount on the land, and then find the extras. Doing it this way round means you never have to go back and ask the seller to wait.</p>

