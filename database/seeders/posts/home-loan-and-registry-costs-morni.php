<h2>Stamp duty and registration</h2>

<p>Both are set by the state of Haryana, not by the seller and not by us. What you pay depends on three things:</p>

<ul>
  <li><strong>The collector rate</strong> for that area &mdash; a government-notified minimum value, which may be above or below your agreed price</li>
  <li><strong>Whether the buyer is a man or a woman</strong> &mdash; Haryana has differing rates</li>
  <li><strong>Whether the property is rural or urban</strong></li>
</ul>

<p>We deliberately do not print a percentage here. These rates are revised, and a number written down today becomes wrong quietly. <strong>Get the exact figure from the tehsil for your specific khasra before you fix your budget.</strong> It takes one visit and removes the worst surprise in the process.</p>

<p>One thing worth knowing: duty is calculated on the collector rate or the sale price, whichever is higher. If a plot is being sold below the notified rate, you still pay duty on the notified rate.</p>

