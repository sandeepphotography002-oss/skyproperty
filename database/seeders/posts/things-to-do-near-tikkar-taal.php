<h2>A picnic done properly</h2>

<p>Most visits here end up being a picnic, so it is worth doing well.</p>

<ol>
  <li>Bring something to sit on — the ground is stony and often damp.</li>
  <li>Find shade before you settle, particularly from April onwards.</li>
