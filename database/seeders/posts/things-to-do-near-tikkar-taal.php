<h2>At and around the lakes</h2>

<ul>
  <li><strong>Sit by the water.</strong> The main activity, and the reason most people come. Bring something to sit on.</li>
  <li><strong>Walk between the two lakes.</strong> Short, easy, and better on foot than by car.</li>
  <li><strong>Birdwatching.</strong> Early morning is much better than the middle of the day.</li>
  <li><strong>Boating</strong>, which has been available here at times. Check the current position before you travel rather than promising it to children.</li>
  <li><strong>Photography</strong>, particularly the hour after sunrise and the hour before sunset.</li>
</ul>

<h2>Walking in the hills</h2>

<p>This is the best thing Morni offers and the least organised. There are tracks, forest paths and terraced field routes in every direction.</p>

<ol>
  <li>Ask locally which way to go rather than trusting a map application.</li>
  <li>Start early, particularly from April onwards.</li>
  <li>Carry water; there is little on the way.</li>
  <li>Wear proper shoes — surfaces are loose in places.</li>
  <li>Tell somebody where you are going if you are walking alone.</li>
  <li>Turn back earlier than you think you need to. Downhill in fading light is the part people underestimate.</li>
</ol>

<h2>Morni village and the fort</h2>

<p>The village below the lakes has the market, a few shops and ordinary hill life. There is an old fort at Morni that people visit; ask locally about current access rather than assuming it is open.</p>

<p>An hour spent in the village is a better use of time than most visitors give it. It is also where you will find food more reliably than at the lakes.</p>

<h2>Simply staying still</h2>

<p>We are aware how this reads on a list of things to do, but it is the honest answer. The people who enjoy Morni most are the ones who arrive without a plan, find somewhere to sit, and stay there.</p>

<ul>
