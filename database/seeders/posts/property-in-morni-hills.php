<h2>Why people buy in Morni Hills at all</h2>

<p>Morni is the only hill station in Haryana. It sits about 45 km from Panchkula and takes an hour and a half to two hours from Chandigarh, depending on where in Morni you are going.</p>

<p>The reason real estate in Morni Hills moves at all comes down to one rule that has nothing to do with the view. Kasauli, Solan and Parwanoo are in Himachal Pradesh, and Himachal restricts the purchase of land by people who are not Himachali. Morni is in Haryana, where no such restriction applies to ordinary plots.</p>

<p>So a buyer from Chandigarh, Delhi or Punjab can buy a residential plot in Morni with a normal registry. That single fact is most of why property in Morni Hills is still affordable compared with the hill stations an hour further up.</p>

