<h2>Where the house would stand</h2>

<p>Views are sold from the road. Houses are built lower, further back, or behind a retaining wall. Stand exactly where the building would sit, at the height it would sit, and look from there.</p>

<ul>
  <li>Sit down. A view from a chair is different from a view standing on a bank.</li>
  <li>Consider the verandah position, since that is where you will actually be.</li>
  <li>Check whether cutting into the slope drops you below the sight line.</li>
  <li>Check what is in the foreground — a wall, a track, a neighbour's roof.</li>
</ul>

<h2>What a valley view costs</h2>

<p>Valley facing plots usually sit on the outer edge of a slope, which brings its own costs.</p>

<ul>
