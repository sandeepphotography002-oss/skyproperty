<h2>Protecting land you are not using</h2>

<p>Unattended land attracts problems, and prevention is far cheaper than remedy.</p>

<ol>
  <li>Mark the boundary physically and visibly. Stones, a bund, a fence line.</li>
  <li>Complete mutation immediately and keep a fresh fard on file.</li>
  <li>Do not allow informal cultivation without a documented arrangement.</li>
  <li>Speak to the neighbours. They will tell you about changes before anyone else.</li>
  <li>Photograph the boundary each visit, dated.</li>
  <li>Deal promptly with any encroachment. Time works against the absent owner.</li>
</ol>

<p>The third point deserves emphasis. Letting a neighbour cultivate as a favour is generous and creates a record you may later have to argue with.</p>

<h2>Agricultural or residential for a holding?</h2>

<ul>
  <li><strong>Agricultural land</strong> — cheapest entry, lowest holding cost, slowest exit, hardest to finance. Good for long patient positions.</li>
  <li><strong>Residential or approved land</strong> — higher entry, wider buyer pool, easier finance, faster exit. Good if the horizon is uncertain.</li>
</ul>

<p>The right choice follows from your horizon, not from the rate.</p>

<h2>Knowing when to sell</h2>

<p>Land holders often have no exit plan at all, which is how positions become permanent by accident.</p>

<ul>
  <li>Set the horizon at purchase, even loosely.</li>
  <li>Review it when something material changes nearby — a road, a colony, a new use.</li>
  <li>Allow a season or more for the sale itself.</li>
  <li>Get the papers ready before you list, not after a buyer appears.</li>
  <li>Be realistic that the pool of buyers is people who want to live or build here.</li>
</ul>

