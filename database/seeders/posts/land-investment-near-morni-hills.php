<h2>The file you should keep</h2>

<p>A land holding is mostly paperwork sitting still. Keeping it in one place, updated, is the cheapest thing you can do for the eventual sale.</p>

<ul>
  <li>Registered sale deed</li>
  <li>Mutation order, and a fresh fard showing your name</li>
  <li>Khasra number and a copy of the relevant village map extract</li>
  <li>Payment receipts for every stage, including the token</li>
  <li>Any right of way document or access agreement</li>
  <li>Correspondence confirming classification</li>
  <li>Dated photographs of the boundary from each visit</li>
  <li>Contact details for the neighbours on each side</li>
</ul>

<p>When you sell, a buyer who is handed this file forms a very different impression from one who is told the papers can be arranged. In a market where buyers are cautious, that impression is worth real money.</p>

<h2>Review it once a year</h2>

<ol>
  <li>Pull a fresh fard and confirm nothing has changed on the record.</li>
  <li>Visit the land and photograph the boundary.</li>
  <li>Check that markers are still in place and visible.</li>
  <li>Note any new construction or activity nearby.</li>
  <li>Update the file, and tell whoever in your family would need to find it.</li>
</ol>

<p>That last point is worth more than it sounds. A great deal of the difficult land in this district is difficult because the person who understood it is no longer available to explain it.</p>

