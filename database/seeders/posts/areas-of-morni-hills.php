<h2>Sun, water and the things maps do not show</h2>

<h3>Which way the slope faces</h3>
<p>South and south-east hold the winter sun longest. A north-facing slope loses light by mid-afternoon in December and stays cold and damp. In June you will not notice. In January you will notice every single day, and so will your heating bill.</p>

<h3>Where the water comes from</h3>
<p>Three answers, and they are not equal. A village line is best. A working borewell is good, but ask what depth the neighbours had to drill to. A seasonal channel runs roughly July to October and is dry the rest of the year — fine for an orchard, not for a house.</p>

<h3>Who is there in February</h3>
<p>Some pockets are lively at weekends in May and nearly empty in winter. If yours is one of those, an empty house needs a caretaker who is genuinely local rather than someone who visits.</p>

<h3>What the neighbours are doing</h3>
<p>Land next door that is farmed behaves differently from land next door that has been sold to somebody planning to build. Ask. In a small place, people know, and they will usually tell you.</p>

