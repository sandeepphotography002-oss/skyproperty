<h2>Why undivided ownership is more common in small settlements</h2>

<p>Where land has not traded for generations, there has been no occasion to divide it formally. Families hold it together, work it together, and the record still names a grandfather.</p>

<ol>
  <li>Pull a fresh fard and count every name on it.</li>
  <li>Ask who else has a claim by inheritance but does not appear on the record.</li>
  <li>Establish whether you are buying the whole holding or one person's undivided share.</li>
