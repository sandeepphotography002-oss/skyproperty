<h2>A realistic first build</h2>

<p>Most people buying a level village plot here are building their first house in the hills. A modest, well built two bedroom house is the version that works, and it is worth being specific about why.</p>

<ul>
  <li><strong>Two bedrooms and a verandah</strong> suits most families and most visit patterns.</li>
  <li><strong>One storey</strong> unless you need the space — it is cheaper, simpler and easier to maintain.</li>
  <li><strong>A covered outdoor space</strong> is used more than an extra room, in this weather.</li>
  <li><strong>Storage for water</strong> sized for several days, not for one.</li>
  <li><strong>Simple, solid finishes.</strong> Damp and closed months are hard on anything delicate.</li>
</ul>

<p>The most common regret we hear is building larger than the number of visits justified. The rooms that stay closed still collect damp and still need maintaining.</p>

<h2>Sequence for a first build</h2>

<ol>
  <li>Buy, register, and complete mutation.</li>
  <li>Mark the boundary physically before anything else.</li>
  <li>Sort the water connection and a storage tank.</li>
  <li>Get the power connection applied for early — it takes longer than people expect.</li>
  <li>Get a local mason to quote per square foot, and a second opinion.</li>
  <li>Build through the dry months and plan around the monsoon rather than through it.</li>
  <li>Get the drainage right before the first wet season, not after it.</li>
</ol>

<p>Nearly every expensive repair on a hill house starts as drainage that was left until later.</p>

