<p>So roughly six good months, weighted to weekends. Any projection that spreads annual revenue evenly across twelve months is not describing Morni.</p>

<h2>Buy a running one, or build?</h2>

<h3>Buying a running stay</h3>
<p>The great advantage is that you can look at what it actually did, rather than what someone thinks it might do.</p>

<ul>
  <li>Ask for two years of occupancy, not one</li>
  <li>Ask which months carried the year</li>
  <li>Ask what the staff cost and how many stayed</li>
  <li>Ask what the licences are and whether they transfer</li>
  <li>Ask why they are selling, and listen to the whole answer</li>
</ul>

<p>A seller who has the numbers ready is a good sign. A seller who talks only about the view is telling you where the strength is not.</p>

<h3>Building your own</h3>
<p>More control, and much slower. You are then doing two hard things at once: a hill build and a new business. If you have not done either, do them one at a time.</p>

<h2>Licences and rules</h2>

<p>A homestay in Haryana can be registered under the state's homestay scheme, which is the ordinary route for a small owner-run place. A larger resort is a commercial operation with the corresponding requirements.</p>

<p>Two things to establish before you pay:</p>

<ul>
  <li><strong>The land classification.</strong> Commercial use of agricultural land is not permitted without the use being changed. Buying farm land and planning rooms on it is a slow road with no guarantee.</li>
  <li><strong>Whether the existing licences transfer,</strong> and on what terms. Ask to see them rather than being told about them.</li>
</ul>

<h2>What it costs to run</h2>

<ul>
  <li><strong>Staff.</strong> The largest ongoing cost, and the hardest thing in a small place. Good staff are scarce and worth keeping.</li>
  <li><strong>Food.</strong> Supplies come up from below. Wastage is a real cost when occupancy is unpredictable.</li>
  <li><strong>Power and backup.</strong> Cuts are longer here, and guests notice.</li>
  <li><strong>Water.</strong> Rooms use a lot, and May is tight in Morni.</li>
  <li><strong>Maintenance.</strong> Every monsoon leaves something. Guests notice that too.</li>
  <li><strong>Marketing.</strong> Listings, commission on bookings, photographs that do the property justice.</li>
</ul>

<p>The quiet months still carry staff, electricity and maintenance. That is the number people leave out.</p>

<h2>What decides whether it works</h2>

<h3>Location, in the narrow sense</h3>
<p>Not "beautiful" — findable. Near Tikkar Taal or Morni village, where visitors already are, beats a spectacular property forty minutes further in that nobody stumbles across.</p>

<h3>The road</h3>
<p>Guests arrive in ordinary cars, often at night, often for the first time. An approach that a local takes in his stride can lose you a booking and a review.</p>

<h3>Someone who is actually there</h3>
<p>Remote-managed small stays go downhill quietly. Either you are there, or you have a manager you trust completely and pay properly.</p>

<h3>Photographs</h3>
<p>People book from pictures. Bad photographs of a good property cost more bookings than most owners realise, and it is the cheapest thing on this list to fix.</p>

<h2>Before you buy a running stay</h2>

<ul class="chk">
  <li>Two years of occupancy figures, month by month</li>
  <li>Staff list, wages, and how long each has been there</li>
  <li>Licences seen, and confirmation they transfer</li>
  <li>Land classification confirmed on the record</li>
  <li>Water source and summer capacity</li>
  <li>Power backup capacity, and its age</li>
  <li>Last three years of monsoon repairs</li>
  <li>Existing bookings, and whether they carry over</li>
  <li>Online reviews read in full, including the bad ones</li>
  <li>The approach driven at night</li>
</ul>

<h2>Who actually stays in Morni</h2>

<p>Knowing your guest changes what you buy. Morni's visitors are not the same crowd as Kasauli's.</p>

<ul>
  <li><strong>Tricity families, one or two nights.</strong> The bulk of it. They drive up Saturday, want food included, and care about parking and a clean bathroom far more than about design.</li>
  <li><strong>Couples on a short break.</strong> Book from photographs, read reviews carefully, and are the group most affected by a difficult approach at night.</li>
  <li><strong>Small groups and offsites.</strong> Worth having capacity for, because one booking fills the place. They ask about food, a bonfire and somewhere to sit together.</li>
  <li><strong>Day visitors.</strong> Numerous at Tikkar Taal, and they do not stay. Do not confuse day footfall with room demand — a busy lake does not fill your rooms by itself.</li>
</ul>

<p>Almost all of it is weekend business. Midweek is quiet nearly all year, and a property priced on seven-night weeks is priced wrong.</p>

<h2>What guests complain about here</h2>

<p>Reviews for hill stays are remarkably consistent, and none of the complaints is about scenery:</p>

<ul>
  <li><strong>The last stretch of road.</strong> Not mentioned in the listing, discovered at night.</li>
  <li><strong>Water.</strong> Especially in May, especially with full occupancy.</li>
  <li><strong>Power cuts</strong> with backup that does not cover the rooms.</li>
  <li><strong>Food</strong> that arrives late, or a kitchen that closes early.</li>
  <li><strong>Damp</strong> after the monsoon, which is a maintenance failure rather than bad luck.</li>
  <li><strong>Nobody in charge</strong> when something goes wrong at nine in the evening.</li>
</ul>

<p>Fix those six and you are ahead of most of the competition, none of which requires a bigger property.</p>

<h2>Staff, honestly</h2>

<p>This is the hardest part of running a stay in a small place, and it is where most owners underestimate the work.</p>

<p>You need a cook, someone for housekeeping, and someone who can handle guests — and in a small operation those may be two people doing three jobs. Good staff are scarce here and are usually already employed. Training somebody takes a season, and losing them mid-season is the sort of problem that shows up in your reviews within a fortnight.</p>

<p>Pay properly and keep people. It costs less than replacing them, and a returning guest usually remembers the person, not the room.</p>

<h2>A fair way to think about the numbers</h2>

<p>Work out what the property costs to run for a full year, including the four quiet months. Then look at what the good six months actually earned last year — not what they could earn.</p>

<p>If that comparison only works with an occupancy figure higher than the property has ever achieved, you are buying a hope. It might come off. Just be clear that that is the purchase.</p>

<h2>The honest summary</h2>

<p><strong>It can work</strong> if you are present or have a manager you trust, the property is findable, the road is easy, and you can carry the quiet months.</p>

<p><strong>It usually does not</strong> if you are buying it as passive income from another city, or if the whole case rests on a view rather than on access and occupancy.</p>

