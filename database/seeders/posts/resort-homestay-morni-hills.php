<p>Every few weeks somebody calls wanting to buy a resort in Morni. The picture in their head is a beautiful property that earns money while they live elsewhere. The reality is a small hospitality business in a hill district, and the two are not close.</p>

<p>That does not mean it is a bad idea. Some of these work well. But you should go in knowing what you are taking on.</p>

<h2>Is the demand real?</h2>

<p>Yes, and this is the strongest thing in Morni's favour. It is the only hill station in Haryana, an hour and a half to two hours from Chandigarh, and weekend traffic from the Tricity is genuine.</p>

<p>What matters is the shape of that demand:</p>

