<h2>The six questions that matter</h2>

<ol>
  <li><strong>Is there hot water in every room, in the evening?</strong> This is what most complaints here are about. Ask specifically about the evening, when everyone showers at once.</li>
  <li><strong>How far from the lakes, in minutes, and is the last stretch motorable?</strong> Kilometres mislead in hills.</li>
  <li><strong>Are meals included, and at what times?</strong> Eating options nearby are limited, so this matters more than usual.</li>
  <li><strong>Is there covered outdoor space?</strong> It decides what an afternoon of rain feels like.</li>
  <li><strong>What is the power backup?</strong> Supply is not uniformly reliable, particularly in the monsoon.</li>
  <li><strong>Is anyone on site overnight?</strong> Worth knowing before you arrive, not after.</li>
</ol>

<p>A place that answers all six clearly is usually well run. Vagueness on the first and third is the most reliable warning sign.</p>

