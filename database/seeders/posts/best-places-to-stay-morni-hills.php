<h2>What a stay costs, roughly</h2>

<p>We will not quote figures that go stale, but the shape is worth knowing. Accommodation in Morni is modest by hill station standards, largely because it is simple and because the season is short.</p>

<ul>
  <li><strong>Homestays</strong> sit at the lower end, often including meals.</li>
  <li><strong>Small resorts</strong> cost more and give you staff, more meal choice and usually better bathrooms.</li>
  <li><strong>Whole property bookings</strong> are surprisingly affordable for a group and are the best value form of comfort here.</li>
  <li><strong>Off season and weekdays</strong> are noticeably cheaper, and often negotiable for longer stays.</li>
</ul>

<p>What varies far more than the price is how well a place is run. A modest homestay with reliable hot water and good food beats an expensive one without either.</p>

