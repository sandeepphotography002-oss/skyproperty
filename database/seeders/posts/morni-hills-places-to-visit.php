<h2>On the way up</h2>

<h3>Panchkula</h3>

<p>Your last reliable stop for fuel, food and anything forgotten. Treat it as a supply point rather than a destination.</p>

<h3>Pinjore</h3>

<p>Known for its historic terraced gardens, and there is a well known temple complex in the area too. It sits on the approach side, which makes it a better stop on the way back than on the way up — the lakes are best early. Confirm current timings before planning around it.</p>

<h3>Kalka</h3>

<p>On the highway towards Shimla and the starting point of the narrow gauge hill railway. Worth a stop if railways interest you, or if you are continuing into Himachal afterwards.</p>

<h2>In Morni</h2>

<h3>Morni village</h3>

<p>Market, shops, school and ordinary hill life below the lakes. The most reliable place for food in the area, and the best place to ask directions from someone who knows.</p>

<h3>Morni fort</h3>

<p>An old fort that visitors go to. Ask locally about current access rather than assuming it is open.</p>

<h3>Tikkar Taal</h3>

<p>The two lakes above the village. The main draw, best in the early morning, and busiest on weekends in season.</p>

<h3>Karoh Peak</h3>

<p>The highest point in Haryana lies in these hills. It attracts walkers. Ask locally about the current route and access before building a day around it.</p>

