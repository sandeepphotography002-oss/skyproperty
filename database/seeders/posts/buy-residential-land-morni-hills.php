<h2>If you are buying from a developer or a colony</h2>

<p>Occasionally land near the hills is offered as part of a layout rather than as an individual plot. The classification question then becomes a question about the whole scheme, and it should be asked differently.</p>

<ol>
  <li>Ask which authority sanctioned the layout, and get the reference number.</li>
