<h2>Fire season, and the margin that prevents trouble</h2>

<p>The dry months before the monsoon are when wooded slopes are most vulnerable, and it is the one seasonal risk that owners of forest side property should plan for rather than react to.</p>

<ol>
  <li>Keep a cleared margin between the building and the tree line — bare ground or short grass, not scrub.</li>
  <li>Clear dry leaf litter from the roof, gutters and against walls before April.</li>
  <li>Do not stack firewood or dry material against the house.</li>
  <li>Keep water stored and a hose or buckets accessible through the dry months.</li>
  <li>Ask neighbours what has happened in past years and what they do.</li>
  <li>Tell your caretaker what to watch for and who to call.</li>
</ol>

<p>None of this is onerous. It is an afternoon of work each spring, and it is the difference between a manageable situation and an unmanageable one.</p>

