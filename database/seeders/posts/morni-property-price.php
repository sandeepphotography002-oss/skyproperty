<h2>Why the same plot gets three different quotes</h2>

<h3>Different units</h3>

<p>One person quotes per marla, the next per kanal, a third per acre. The numbers look wildly different and describe the same land. Always ask which unit, then convert before comparing.</p>

<h3>Different land</h3>

<p>Some sellers quote for the flat portion only, others for the whole khasra including the slope that cannot be built on. Ask what the usable area is, and walk it.</p>

<h3>Different papers</h3>

<p>Land with a clean single-owner registry is a different product from land held by six heirs who have not divided it. The second is cheaper for a reason, and the reason may cost you two years.</p>

<h2>How to sanity-check a quoted rate</h2>

<ol>
  <li>Ask for the unit and convert it. One acre is eight kanal; one kanal is twenty marla.</li>
  <li>Ask what the road is — tar, kaccha, or a right of way across someone else's field.</li>
  <li>Stand on the plot and look at the slope. If you cannot picture the house, ask what the levelling will cost.</li>
  <li>Ask whose name is on the registry, and how many names.</li>
  <li>Ask where water comes from, and whether it runs in May.</li>
  <li>Ask what the neighbours paid, if anyone will say. In a small market this is often known.</li>
</ol>

<p>If a rate survives those six questions, it is probably a real rate. If the seller becomes vague at question three or four, the price is not the problem.</p>

<h2>What buyers most often get wrong</h2>

<p>Two mistakes come up again and again.</p>

