<h2>What it roughly costs</h2>

<p>We will not quote figures that go stale, but the shape of the spending is useful to know.</p>

<ul>
  <li><strong>Accommodation</strong> is the main cost, and modest by hill station standards.</li>
  <li><strong>Fuel</strong> for roughly 110 km of driving, plus the climb.</li>
  <li><strong>Food</strong> is usually included or cheap; there is little to spend on.</li>
  <li><strong>Everything else</strong> — there are almost no tickets, no shopping and no activities to pay for.</li>
</ul>

<p>Morni is one of the cheaper weekends available from the Tricity, largely because there is nothing to buy.</p>

<h2>Where to eat across the weekend</h2>

<p>Food needs a little planning here, because options are few and kitchens are small.</p>

<ul>
  <li><strong>Breakfast and dinner</strong> at your stay, almost always. Tell them your timings the night before.</li>
  <li><strong>Lunch</strong> at your stay, in Morni village, or as a picnic you carried.</li>
  <li><strong>Tell them if you will be out</strong> at a mealtime; small kitchens cook to a count.</li>
  <li><strong>Carry snacks</strong> regardless, particularly with children.</li>
  <li><strong>Do not plan a restaurant meal.</strong> There is very little of that here.</li>
</ul>

<h2>Variations</h2>

<ul>
  <li><strong>Friday evening departure</strong> buys an extra morning. Only if you know the hill road.</li>
  <li><strong>With small children</strong> — stay nearer the village, plan shorter outings, carry food.</li>
  <li><strong>With elderly parents</strong> — motorable access to the door, no long walks, take the climb slowly.</li>
  <li><strong>For photography</strong> — same plan, but be out at both first light and sunset both days.</li>
  <li><strong>In the monsoon</strong> — same plan, shorter walks, and watch the road for the return.</li>
</ul>

<h2>Mistakes that spoil the weekend</h2>

<ul>
  <li>Arriving at midday in May, hot and tired, and trying to do the lakes immediately.</li>
  <li>Planning a long drive on Saturday afternoon.</li>
  <li>Leaving the descent until after dark on a first visit.</li>
  <li>Scheduling something at home for Sunday evening.</li>
  <li>Skipping Sunday morning by sleeping in. It is the best part.</li>
</ul>

<h2>A packing list for two nights</h2>

<ol>
  <li>Warm layers November to February; a jacket rather than a sweater.</li>
  <li>Rain protection July to September, plus a spare set of dry clothes.</li>
  <li>Proper shoes with grip.</li>
  <li>Water and snacks for the drive and the day.</li>
  <li>Torch, since power cuts happen and paths are unlit.</li>
  <li>Cash; not everything takes cards.</li>
  <li>All regular medicines and basic first aid.</li>
  <li>Mosquito protection after the rains.</li>
  <li>Something to sit on outdoors.</li>
  <li>A book, and less of a plan than you think you need.</li>
</ol>

<h2>If you have only one night</h2>

<ul>
  <li>Leave earlier — six thirty rather than seven thirty.</li>
  <li>Do the lakes on arrival, not the next morning.</li>
  <li>Keep the afternoon free and the evening outside.</li>
  <li>Be up at first light; it is your only morning.</li>
  <li>Leave after an early lunch rather than staying late.</li>
</ul>

<p>One night works. It simply asks you to be more disciplined about the two good hours.</p>

<h2>What people actually ask us</h2>

