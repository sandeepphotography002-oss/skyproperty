<h2>Visiting well</h2>

<p>This is a small area with a growing number of visitors and very little infrastructure to absorb them. A few things make a genuine difference.</p>

<ul>
  <li><strong>Take your rubbish home.</strong> There is little collection up here, and what is left behind stays.</li>
  <li><strong>Keep music to yourself.</strong> Sound travels a long way in hills, and quiet is what most people came for.</li>
  <li><strong>Park where you are meant to.</strong> The roads are narrow and blocking them affects people who live here.</li>
  <li><strong>Do not feed animals.</strong> It changes their behaviour and creates problems for residents.</li>
  <li><strong>Buy locally where you can.</strong> Tea, food, a homestay — it is how tourism benefits the place rather than just passing through it.</li>
  <li><strong>Ask before photographing people.</strong> Ordinary courtesy, and often forgotten.</li>
</ul>

<h2>What visitors most often get wrong</h2>

<ul>
  <li>Arriving at midday in May, when it is hot and the lakes are at their least appealing.</li>
  <li>Expecting a hill station with restaurants and shops.</li>
  <li>Promising children boating without checking it is running.</li>
  <li>Leaving the descent until after dark on a first visit.</li>
  <li>Coming on a Sunday in April expecting solitude.</li>
</ul>

<h2>What tourism means for the area</h2>

<p>Visitor numbers support homestays, small resorts, shops and drivers, and that income matters here. They also bring traffic, litter and pressure on a place that has never had much infrastructure.</p>

<p>For anyone buying property nearby, this is worth understanding on both sides: the tourism is real and it is why a rooms business can work, and it is also why a plot on the visitor route is not the place to buy if you want silence at weekends.</p>

<h2>Choosing a homestay here</h2>

<p>Accommodation in Morni is personal rather than standardised, which means the difference between a good stay and a poor one is larger than it would be in a town with hotels. A few questions sort it out.</p>

<ol>
  <li><strong>Is there hot water in every room, in the evening?</strong> This is what most complaints are about.</li>
  <li><strong>How far from the lakes, and is the last stretch motorable?</strong> Ask in minutes, not kilometres.</li>
  <li><strong>Are meals included, and at what times?</strong> Options nearby are limited, so this matters more than usual.</li>
  <li><strong>Is there a covered outdoor space?</strong> It decides what an afternoon of rain feels like.</li>
  <li><strong>What is the power backup?</strong> Supply is not uniformly reliable.</li>
  <li><strong>Is anyone on site overnight?</strong> Worth knowing before you arrive.</li>
</ol>

<p>Read recent reviews rather than looking only at photographs, and be a little wary of listings whose pictures all appear to be from the same clear October morning.</p>

<h2>Travelling with older visitors or small children</h2>

<ul>
  <li>Take the hill section slowly; it is the part that tires people.</li>
  <li>Choose accommodation with motorable access right to the door.</li>
  <li>Ask about steps — many hill properties have plenty.</li>
  <li>Carry medicines and anything essential; there is little available up here.</li>
  <li>Keep children away from unfenced lake edges.</li>
  <li>Plan shorter days than you would elsewhere.</li>
</ul>

