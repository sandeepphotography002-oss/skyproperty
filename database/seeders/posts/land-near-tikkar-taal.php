<h2>Undivided ownership, which is common here</h2>

<p>Land in this belt has usually passed down two or three generations without ever being formally divided. It is not a defect and it is not unusual — it simply has to be handled properly.</p>

<ol>
  <li>Pull a fresh fard and count every name on it.</li>
  <li>Ask who else has a claim by inheritance but does not appear on the record.</li>
  <li>Establish whether you are buying the whole holding or one person's share.</li>
  <li>If it is a share, establish exactly which part of the ground that share corresponds to.</li>
  <li>Confirm that every recorded owner will attend the registry, and on what date.</li>
  <li>Have an advocate involved from the start, not once a problem appears.</li>
</ol>

<p>A sale here stalls far more often over an absent brother than over anything to do with the land. Sorting it out early costs a few weeks; discovering it late can cost the purchase.</p>

