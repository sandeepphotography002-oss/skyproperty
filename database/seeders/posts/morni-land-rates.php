<h2>Why hill land is quoted differently from city land</h2>

<h3>Usable area is not total area</h3>

<p>In a city plot, the whole rectangle is buildable. On a slope, part of the holding is a cut face or a drop. The paper area and the useful area are different numbers, and only one of them matters to you.</p>

<h3>Terraces are counted, slopes are argued about</h3>

<p>Farm land here is often in terraces. Each terrace is flat and countable. The banks between them are not. Sellers include them, buyers do not, and the negotiation happens there.</p>

<h3>Small parcels cost more per unit</h3>

<p>A ten marla plot will almost always carry a higher rate per marla than a two acre holding. That is normal, not a trick. Small, level, road-touch parcels are the scarce thing in Morni.</p>

<h2>Worked example</h2>

<p>Suppose you are shown two properties.</p>

<ul>
  <li><strong>Plot A</strong> — 10 marla, level, inside the village, quoted at a per marla rate.</li>
  <li><strong>Plot B</strong> — 4 kanal on a gentle slope with road touch, quoted as a total.</li>
</ul>

<p>Plot B is 80 marla, eight times the size of Plot A. If the total for B is less than eight times the total for A, then B is cheaper per unit — but B may need levelling and a retaining wall, and A already sits inside the village with water and power at the boundary.</p>

<p>Neither is automatically the better buy. The point is that you can only have the argument once both are in the same unit.</p>

<h2>What the paperwork calls your land</h2>

<p>The revenue record does not use the word plot. It uses a khasra number and an area in kanal and marla. When you check the jamabandi, the figure there is the one that will be registered, and it will not always match what the seller told you on the phone.</p>

<ul>
  <li>Get the khasra number early.</li>
  <li>Match the area on the record to the area you were quoted.</li>
  <li>If they differ, ask why before anything else is discussed.</li>
