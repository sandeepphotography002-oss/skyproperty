<h2>Three ways buyers make a small budget go further</h2>

<h3>1. Buy land now, build later</h3>

<p>The most common and often the wisest. Land has almost no holding cost — keep the boundary clear and the papers current. You build when you can, in stages if necessary.</p>

<p>Conditions: confirm classification before buying, and choose a plot a vehicle reaches so that building later is not disproportionately expensive.</p>

<h3>2. Buy level ground rather than more ground</h3>

<p>Levelling and retaining are where modest budgets disappear. A small level plot in a village often produces a finished house for less than a larger sloped plot at a lower rate.</p>

<h3>3. Build small and build well</h3>

<p>Two rooms built properly, with a sound roof, good drainage and hot water, is a better hill house than four rooms built thinly. It also costs less to maintain, which matters for years afterwards.</p>

