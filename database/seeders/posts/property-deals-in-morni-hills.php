<h2>On negotiation</h2>

<p>Bargaining is expected, but the style matters. Reasoned offers are taken seriously; aggressive ones often end the conversation in a market where the seller has no urgency.</p>

<ul>
  <li>Offer with a reason — a defect, a repair cost, a comparable rate nearby.</li>
  <li>Ask what is included, because that is often easier to move than price.</li>
  <li>Expect two or three rounds, not ten.</li>
  <li>Do not use urgency as a tactic. Nobody here is in a hurry.</li>
  <li>Keep it courteous. This is a small place and you will meet these people again.</li>
</ul>

<h2>On token money</h2>

<p>This is where the most avoidable damage happens.</p>

<ol>
  <li><strong>Never pay a token before the record check.</strong> Once money has moved, your position weakens considerably.</li>
  <li><strong>Get a written receipt</strong> stating the property, the amount, and what happens if the deal does not proceed.</li>
  <li><strong>Agree the conditions.</strong> What if a co-owner refuses? What if classification turns out otherwise?</li>
  <li><strong>Keep it modest.</strong> A token confirms intent; it is not part payment for a property you have not verified.</li>
  <li><strong>Pay traceably.</strong> Cash without a receipt has no standing anywhere.</li>
</ol>

<h2>What should be agreed in writing before registry</h2>

<ul>
  <li>The price, and what it includes — building, trees, fittings, standing crop.</li>
  <li>Who bears stamp duty and registration, if it departs from custom.</li>
  <li>The registry date, and who must attend.</li>
  <li>What happens if an owner cannot attend.</li>
  <li>The boundary, and who marks it.</li>
  <li>When possession passes.</li>
</ul>

<h2>Where deals fall apart</h2>

<p>In our experience, in this order:</p>

<ol>
  <li><strong>A co-owner who will not or cannot attend.</strong> By far the most common.</li>
  <li><strong>Classification turning out differently from what was assumed.</strong></li>
  <li><strong>An area mismatch discovered late.</strong></li>
  <li><strong>Access that turns out not to be recorded.</strong></li>
  <li><strong>A buyer treating a verbal understanding as binding.</strong></li>
</ol>

<p>Four of these five are prevented by doing the record check before the token, which is the single most useful habit in this market.</p>

<h2>The dealer's role, honestly</h2>

<p>A dealer here typically introduces the property, arranges viewings, helps with the record work and coordinates the registry. Commission is customary and should be discussed openly at the start rather than assumed.</p>

<p>Ask any dealer, including us, what they are being paid and by whom. A dealer paid by both sides has a different interest from one paid by you.</p>

<h2>If you are buying from a distance</h2>

<p>Plenty of buyers here live in Delhi, Mumbai or abroad. It is workable, and it needs more structure than a local purchase.</p>

<ol>
  <li><strong>Appoint an advocate locally</strong> before you start looking, not after you find something.</li>
  <li><strong>Get the record work done independently</strong> of the dealer showing you the property.</li>
  <li><strong>Ask for dated photographs and video of the boundary walk</strong>, with the seller present.</li>
  <li><strong>Visit once before the token</strong>, even if only for a day. There is no substitute.</li>
  <li><strong>Be present at registry</strong>, or have a properly drawn power of attorney that expressly covers purchase.</li>
  <li><strong>Arrange a caretaker before possession</strong> if there is a building.</li>
</ol>

<p>What we would not advise is completing a first purchase entirely remotely. Access, slope and water are judged by standing on the ground, and photographs flatter all three.</p>

<h2>Paying, and keeping a record of it</h2>

<ul>
  <li>Pay traceably at every stage, including the token.</li>
  <li>Get a written receipt for each payment naming the property.</li>
  <li>Keep the payment record with the deed and the mutation order.</li>
  <li>If several people are contributing, record who paid what.</li>
  <li>Do not settle any part of the price in a way you cannot evidence later.</li>
</ul>

<p>This matters less on the day and considerably more in five years, when you or your family need to show how the property was acquired.</p>

<h2>What buyers actually ask us</h2>

<ul>
  <li>Is a verbal agreement binding? Treat it as intent, not a contract. Get terms written.</li>
  <li>Can I withdraw after paying a token? It depends on what the receipt says. That is why the receipt matters.</li>
  <li>How much is a normal token? Modest. Anyone asking for a large one before records are clear should be questioned.</li>
  <li>Do I need to be present throughout? For registry, yes. For the rest, not necessarily.</li>
</ul>

