<h2>1. You want to double your money in three years</h2>

<p><strong>Verdict: no. Do not buy here.</strong></p>

<p>Morni is a slow market. Buyers come mostly from the Tricity, mostly in the pleasant months, and a sale can take a season or more. A short horizon and a thin market are a bad combination whatever the entry price.</p>

<h2>2. You want land you will hold for ten years or more</h2>

<p><strong>Verdict: reasonable, with conditions.</strong></p>

<p>You get more ground per rupee than anywhere comparable within two hours of Chandigarh, and you buy through an ordinary registry rather than a permission process. Conditions: buy a plot a vehicle already reaches, insist on clean single owner title, and accept that your money is genuinely locked.</p>

<h2>3. You want a weekend house your family will use</h2>

<p><strong>Verdict: yes, if you will actually come.</strong></p>

<p>Ninety minutes from Panchkula is close enough to use, which is the whole argument. Be honest about the number of weekends. A house used ten times a year still needs a caretaker, monsoon repairs and boundary clearing.</p>

<h2>4. You want rental income</h2>

<p><strong>Verdict: possible, as a business, not as passive income.</strong></p>

<p>Demand is real from March to June and again in October, weekend led, from Tricity visitors. That means a limited number of good nights carrying a full year of staff and fixed costs. It works for owners who are present or have a capable manager. It does not work as something you check on quarterly.</p>

<h2>5. You want farm land or an orchard</h2>

<p><strong>Verdict: yes, and it is underrated.</strong></p>

<p>Terraced land here is worked, water exists in most valleys, and the entry price per acre is low. This suits buyers who want the land itself rather than a return, and it carries the lowest holding cost of everything on this list.</p>

