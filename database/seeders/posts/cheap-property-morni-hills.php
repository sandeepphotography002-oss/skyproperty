<h2>An hour on site tells you most of it</h2>

<ol>
  <li>Walk the uphill side first. Look for damp, loose bank and where water enters.</li>
  <li>Look up at every ceiling for stains, and at fresh paint in only some rooms.</li>
  <li>Open every tap and flush every toilet. Watch how fast water drains.</li>
  <li>Ask to see the water storage and be told its capacity.</li>
  <li>Look at the electrical board. Count circuits; ask the sanctioned load.</li>
  <li>Walk the outside of the retaining walls and look for cracks and bulges.</li>
  <li>Ask which parts were added later, and when.</li>
  <li>Ask what has been repaired in the last three years, and by whom.</li>
</ol>

<p>Honest sellers answer these easily. Vague answers to the last two are the most reliable warning sign in the whole visit.</p>

<h2>Cheap for an acceptable reason</h2>

<p>Not every low price is a defect. These are the reasons we would be comfortable with:</p>

<ul>
  <li>The owner needs a quick sale for personal reasons.</li>
  <li>The house is old fashioned but structurally sound.</li>
  <li>It is far from the main road and the buyer pool is small.</li>
  <li>It is unfurnished when comparable properties are furnished.</li>
  <li>The land is agricultural and priced accordingly, with no building claim attached.</li>
</ul>

<h2>Cheap for a reason to walk away from</h2>

<ul>
  <li>The building sits partly outside the recorded boundary.</li>
  <li>Retaining structures are failing and nobody will discuss it.</li>
  <li>Ownership is disputed rather than merely shared.</li>
  <li>There is no reliable dry season water and no realistic prospect of it.</li>
  <li>The seller will not put anything in writing.</li>
</ul>

<h2>The arithmetic that settles it</h2>

<p>Take the asking price. Add an honest figure for the roof, the water, the wiring and any retaining work. Compare the total with a sound property at a higher asking price.</p>

<p>Buyers who do this find that roughly half of cheap properties are genuinely cheap and the other half are simply someone else's deferred maintenance being transferred to them.</p>

<h2>Negotiating with a repair list</h2>

<p>The strongest position on a cheap built property is not a lower offer. It is a written list of what needs doing, with rough costs beside it.</p>

<ol>
  <li>Walk the property with a local builder and note every item.</li>
  <li>Put rough figures against each — roof, drainage, wiring, plumbing, retaining work.</li>
  <li>Total it, and share the list with the seller.</li>
  <li>Make an offer that references the total rather than a round number.</li>
  <li>Be willing to leave the list with them. Sellers often come back.</li>
</ol>

<p>This changes the conversation from opinion to arithmetic. A seller can dispute your offer; they cannot easily dispute a cracked retaining wall you have both looked at.</p>

<h2>What to do in the first three months</h2>

<p>If you do buy a cheap property, sequence the work. Trying to do everything at once wastes money and leaves the house unusable for a season.</p>

<ul>
  <li><strong>First: water in.</strong> Storage, pump, hot water. Nothing else matters if you cannot stay there.</li>
  <li><strong>Second: water out.</strong> Drains, roof, and anything above the house that sends water at it.</li>
  <li><strong>Third: safety.</strong> Wiring and any structural item a builder flagged.</li>
  <li><strong>Fourth: comfort.</strong> Kitchen, bathrooms, paint, furnishing.</li>
  <li><strong>Last: appearance.</strong> The part everyone wants to do first.</li>
</ul>

<p>A monsoon arriving before the roof and drainage are dealt with will undo any cosmetic work you did ahead of them.</p>

