<p>On a small plot, the view is whatever the plot has. On a farmhouse holding of an acre or more, you decide — and most people decide badly, by putting the house where the road already reaches rather than where the land is best.</p>

<p>This page is about making that decision deliberately.</p>

<h2>The four candidate positions</h2>

<table>
  <thead>
    <tr><th>Position</th><th>Gains</th><th>Costs</th></tr>
  </thead>
  <tbody>
    <tr><td>Where the road already reaches</td><td>Cheapest to build and service</td><td>Often the worst outlook and least privacy</td></tr>
