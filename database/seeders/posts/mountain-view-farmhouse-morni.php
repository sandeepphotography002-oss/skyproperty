  </tbody>
</table>

<p>Our usual advice is the third. A flat terrace part way up gives you outlook without the exposure of a summit, and the cost of a short access spur is smaller than people expect.</p>

<h2>Walk the whole holding before deciding</h2>

<ol>
  <li>Walk every terrace and stand on each one, seated if you can.</li>
  <li>Note the outlook from each, and where the sun is at that hour.</li>
  <li>Come back at a different time of day and repeat.</li>
  <li>Note where water runs during and after rain.</li>
  <li>Note where the wind comes from — usually more noticeable higher up.</li>
  <li>Consider where the approach spur would come from, and what it would cost.</li>
</ol>

<p>An afternoon spent doing this before you build is worth more than any amount of design work afterwards, because the position cannot be changed once foundations are in.</p>

<h2>Practical constraints that override the view</h2>

<ul>
  <li><strong>Water.</strong> Building high means lifting water higher. Know where the source is first.</li>
  <li><strong>Drainage.</strong> Never site below a natural water course, however good the outlook.</li>
  <li><strong>Access for construction.</strong> A position a truck cannot reach adds substantially to build cost.</li>
  <li><strong>Slope stability.</strong> Take a local builder's view on any position needing heavy cutting.</li>
  <li><strong>Setback from boundaries</strong>, which limits how close to the edge you can build.</li>
</ul>

<h2>Designing the house around the outlook</h2>

<ul>
  <li>Put the verandah and main living space towards the view, service areas behind.</li>
  <li>Make the verandah deep enough to sit in through rain and through May afternoons.</li>
  <li>Keep the foreground clear — a boundary wall in the middle distance ruins a good outlook.</li>
  <li>Plant for shade on the exposed side, not in the sight line.</li>
  <li>Place the approach so that arriving does not cut through the view from the verandah.</li>
</ul>

<h2>Keeping the view after you build</h2>

<ul>
  <li>Establish what is beyond your boundary in the sight line, and who owns it.</li>
  <li>Check whether that land is classified for building.</li>
  <li>Watch tree growth on your own land as well as beyond it.</li>
  <li>If a small parcel in front is available, consider buying it at the time you buy the holding.</li>
</ul>

<h2>Live on the land before you build on it</h2>

<p>The best decision available to anyone buying a farmhouse holding is also the cheapest: wait a year before choosing where the house goes.</p>

<ul>
  <li>Visit through all four seasons and note where you naturally end up sitting.</li>
  <li>See where water runs in the monsoon, which no survey will tell you as clearly.</li>
  <li>Learn where the wind comes from, and at what time of year.</li>
  <li>Notice where the sun falls at the hours you would actually use the house.</li>
  <li>Find out which terraces stay wet and which drain quickly.</li>
</ul>

<p>Owners who build in the first excited month frequently site the house where the road already reaches. Owners who wait a year almost always choose somewhere else, and are happier for it.</p>

<h2>The approach spur, costed properly</h2>

<p>If the best position needs a short access road built to it, price that before ruling it out.</p>

<ol>
  <li>Get a local contractor to walk the line and give a figure.</li>
  <li>Ask what it needs to carry — a car, or a loaded truck during construction.</li>
  <li>Ask how it will drain, since a track that channels water is worse than no track.</li>
  <li>Check it stays on your own land, or that any crossing is recorded.</li>
  <li>Compare the cost against the value of the better position over thirty years.</li>
</ol>

<p>In our experience the spur usually costs less than buyers fear, and a badly sited house costs more than they expect.</p>

<h2>What buyers actually ask us</h2>

<ul>
  <li>Should I build on the highest point? Usually not. Exposure and water lifting cost more than the extra outlook is worth.</li>
  <li>How much does an access spur cost? Less than most people fear, and it is worth pricing before choosing a position.</li>
