<h2>Buying farm land you intend to actually farm</h2>

<p>This is the main reason people buy here, and it deserves a different set of questions from a plot purchase.</p>

<ol>
  <li><strong>What has been grown here for the last three years?</strong> Check the answer against girdawari rather than taking it on trust.</li>
  <li><strong>Has the land been left fallow, and for how long?</strong> Ground out of use for years takes a season or two to come back.</li>
  <li><strong>What is the irrigation, precisely?</strong> Canal rotation with days and frequency, or borewell with depth and yield.</li>
  <li><strong>How does a tractor reach every part of it?</strong> Not just the roadside edge.</li>
  <li><strong>Who is cultivating it now?</strong> If someone other than the owner, establish the arrangement in writing.</li>
  <li><strong>Where is the nearest mandi</strong>, and how do neighbours move their produce?</li>
</ol>

