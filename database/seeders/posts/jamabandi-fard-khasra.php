  <li>You pull the fard for that khasra and read the ownership.</li>
  <li>You check the jamabandi for history and share.</li>
  <li>You trace mutation entries to confirm past transfers completed.</li>
  <li>Your advocate reads all of it before you pay a token.</li>
</ol>

<h2>Words you will also hear</h2>

<ul>
