  <li><strong>Patwari</strong> — the revenue official who maintains these records at village level.</li>
  <li><strong>Shajra</strong> — the village map showing khasra shapes.</li>
  <li><strong>Girdawari</strong> — the crop inspection record, which shows who has actually been cultivating.</li>
</ul>

<p>Girdawari is worth a moment. If someone other than the owner has been cultivating for a long period, ask on what basis. It is usually nothing, and occasionally it is the whole story.</p>

