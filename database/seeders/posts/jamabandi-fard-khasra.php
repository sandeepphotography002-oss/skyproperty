<p>Put simply: the khasra says <em>where</em>, the jamabandi says <em>whose</em>, and the fard is the printout you carry.</p>

<h2>Khasra — the ground itself</h2>

<p>Every parcel of agricultural land has a khasra number. It appears on the village map, so the number can be traced to an actual shape on actual ground.</p>

<h3>What a buyer should do</h3>

<ul>
  <li>Get the khasra number in writing before anything else.</li>
  <li>Look at it on the village map alongside the seller.</li>
  <li>Walk the boundary and confirm the shape matches.</li>
  <li>If the sale is of part of a khasra, understand exactly how the split will be done.</li>
</ul>

<p>Land that has been cultivated for generations drifts. Terraces get extended, walls get moved. The map and the ground disagreeing is common and is not always dishonesty, but it must be settled before money moves.</p>

<h2>Jamabandi — the record of rights</h2>

<p>The jamabandi is prepared for a whole village and revised on a cycle. It lists holdings with owners, shares and cultivation details.</p>

<h3>The columns that matter to you</h3>

<ul>
  <li><strong>Owner names.</strong> Count them. One name is simple; six names means six people at registry.</li>
  <li><strong>Share.</strong> Written as a fraction. Understand who owns how much before you negotiate.</li>
  <li><strong>Cultivator.</strong> If someone other than the owner is shown cultivating, ask why and on what basis.</li>
  <li><strong>Area.</strong> In kanal and marla. Match this to what you were quoted.</li>
  <li><strong>Kind of land.</strong> This is where classification appears.</li>
</ul>

<h3>The trap</h3>

<p>A jamabandi is a snapshot from its revision year. Things change between revisions. That is exactly what the fard is for.</p>

<h2>Fard — the current extract</h2>

<p>The fard is an extract for a specific holding, issued now. It is what you actually take to a lawyer, a bank or a registering office.</p>

<ul>
  <li>Get a recent one, not a copy the seller has had in a drawer for two years.</li>
  <li>Check the names against the identity documents of the people you are dealing with.</li>
  <li>Check the area against the quote.</li>
  <li>Check for any noted charge or dispute.</li>
</ul>

