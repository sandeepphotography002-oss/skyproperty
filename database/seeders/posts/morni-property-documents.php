<h2>The ones people forget</h2>

<h3>Family and succession papers</h3>

<p>A great deal of Morni land is inherited and never formally divided. If the record shows one name but four brothers have a claim, you need the succession position settled and every relevant person present at registry. This is the single most common cause of a stalled sale here.</p>

<h3>Power of attorney, if anyone is acting for someone else</h3>

<p>Read it. Check it covers sale, not just management, and check it has not been revoked. A sale on a defective power of attorney is a problem that surfaces years later.</p>

<h3>Classification of the land</h3>

<p>Agricultural, residential or something else. This decides what you may build and how the purchase proceeds. Do not accept a verbal answer; have it confirmed.</p>

<h3>Access rights</h3>

<p>If the approach crosses someone else's land, ask what right of way exists and whether it is recorded. A road that works today because of a neighbour's goodwill is not a road you own.</p>

<h2>Step by step verification</h2>

<ol>
  <li>Get the khasra number in writing from the seller.</li>
  <li>Pull the jamabandi and the fard for that khasra.</li>
  <li>Read the ownership column yourself. Count the names.</li>
  <li>Match the area on record to the area you were quoted.</li>
  <li>Trace how the seller acquired it, and check mutation was completed.</li>
  <li>Ask about loans or charges on the land.</li>
  <li>Confirm classification with the district office.</li>
  <li>Walk the boundary with the seller and a neighbour present.</li>
  <li>Confirm the approach and any right of way.</li>
  <li>Have a local advocate read everything before you pay a token.</li>
</ol>

<h2>Red flags worth stopping for</h2>

<ul>
  <li>The seller cannot produce the khasra number quickly.</li>
  <li>The record area and the quoted area differ and nobody can explain why.</li>
  <li>More names on the jamabandi than people at the meeting.</li>
  <li>Pressure to pay a token before papers are seen.</li>
  <li>An assurance that conversion is a formality.</li>
  <li>A boundary that the neighbour describes differently from the seller.</li>
</ul>

<p>None of these means the deal is bad. Every one of them means stop, ask, and get an answer in writing before money moves.</p>

