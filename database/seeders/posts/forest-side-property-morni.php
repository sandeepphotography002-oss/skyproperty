<h2>The questions to have answered in writing</h2>

<ol>
  <li>Where exactly does my boundary run, marked on the ground and matched to the record?</li>
  <li>What is the status of the adjoining land, and who administers it?</li>
  <li>Are there restrictions on construction within any distance of that boundary?</li>
  <li>Does my approach cross land I do not own, and on what recorded basis?</li>
