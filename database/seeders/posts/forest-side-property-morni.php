  <li>Are there any wildlife or protected area provisions applying here?</li>
  <li>Is anything notified — acquisition, plantation, or a change of status?</li>
</ol>

<p>Get answers from the authorities rather than from the seller. A seller repeating what they were told twenty years ago is not evidence, even when they are being entirely honest.</p>

<h2>Why a tree line is not a boundary</h2>

<p>On the ground, where cultivation stops and trees begin looks like a boundary and is usually treated as one locally. It is not necessarily where the record says your land ends.</p>

<ul>
  <li>Walk the boundary with the seller and an adjoining holder present.</li>
  <li>Match what you walked to the area and shape on the fard and the shajra.</li>
  <li>Mark it physically with something that survives a monsoon.</li>
  <li>Photograph the markers, dated, and keep the photographs with your papers.</li>
  <li>Re-mark it if markers are lost. An unmarked boundary beside forest invites disagreement.</li>
</ul>

<h2>Practical living considerations</h2>

<ul>
  <li>Keep a cleared margin between building and tree line, for fire safety and falling branches.</li>
  <li>Expect leaf litter in drains, and clear before each monsoon.</li>
  <li>Secure food, waste and water storage — these hills have real wildlife.</li>
  <li>Expect more shade and damp, particularly on north facing wooded slopes.</li>
  <li>Take neighbours' advice seriously; they have solved these problems already.</li>
</ul>

