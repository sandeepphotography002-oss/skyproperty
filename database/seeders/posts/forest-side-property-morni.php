  <li>Privacy on at least one boundary, permanently.</li>
</ul>

<h2>Access that crosses land you do not own</h2>

<p>On forest side plots the approach frequently runs along or through land belonging to somebody else, or to nobody obvious. That works until it does not, and it is entirely resolvable in advance.</p>

<ol>
  <li>Trace the approach from the public road to the plot, and identify who owns each stretch.</li>
  <li>Establish whether any right of way is recorded, or whether it is use by custom.</li>
  <li>If it crosses the seller's remaining land, make the right of way part of the deed.</li>
  <li>If it crosses forest or common land, ask the administering authority what the position is.</li>
  <li>Check the width is enough for a construction vehicle, not only a car.</li>
  <li>Establish who maintains it after the monsoon.</li>
</ol>

<p>A plot with an unrecorded approach is worth less than one without, whatever the outlook, because the next buyer will ask exactly this question.</p>

<h2>Keeping records for a boundary that matters</h2>

<ul>
  <li>Mark the boundary physically with something that survives a season.</li>
  <li>Photograph every marker, dated, on each visit.</li>
  <li>Keep the fard, the shajra extract and the photographs together.</li>
  <li>Re-mark promptly whenever a marker is lost or moved.</li>
  <li>Note the names and contacts of the holders on each side.</li>
</ul>

<p>Beside forest, where there is no wall and no neighbour's house to reference, a documented boundary is the only version of the boundary that will survive a disagreement.</p>

