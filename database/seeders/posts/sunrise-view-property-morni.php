<h2>Winter afternoons, and how to handle them</h2>

<p>This is the real cost of east facing and the one that surprises owners in their first December. The house goes into shade early, and short days make that noticeable.</p>

<ul>
  <li><strong>A fireplace or good heating.</strong> It earns its place from November to February and adds to the pleasure of being there.</li>
  <li><strong>Insulation, particularly in the roof.</strong> Retaining the morning warmth matters more than gaining afternoon sun.</li>
  <li><strong>A south facing corner.</strong> Even on an east facing plot, one room or a corner of the verandah facing south gives you somewhere warm at three in the afternoon.</li>
  <li><strong>Thermal mass.</strong> Masonry that absorbs the morning sun releases it into the evening.</li>
  <li><strong>Wind shelter on the exposed side</strong>, which affects comfort as much as sun does.</li>
</ul>

