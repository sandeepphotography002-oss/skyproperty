<h2>Hiring a taxi instead of driving</h2>

<p>A sensible option if the hill road does not appeal, and one many Tricity visitors choose.</p>

<ol>
  <li>Hire from Panchkula or Chandigarh for the whole day rather than one way.</li>
  <li>Agree the waiting time in advance; there is nothing for a driver to do at the bottom.</li>
  <li>Agree the route and the stops before setting off.</li>
  <li>Confirm the driver has done the hill road before.</li>
