<h2>The May test</h2>

<p>If you take one thing from this page: <strong>see the plot in May.</strong></p>

<p>May is when Morni's water is tightest. A channel that looked like a stream in August will be a dry bed. A borewell that filled a tank in October will be slower. Everything looks generous after the monsoon and honest in May.</p>

<p>If you cannot visit in May, ask a neighbour &mdash; not the seller &mdash; what happens there in summer. People will tell you.</p>

<h2>Water during construction</h2>

<p>People plan water for living in and forget water for building. A house needs a great deal of it over several months.</p>

<p>On a plot with only a seasonal channel that means tankers on a narrow hill road for the length of the build. It is both slow and expensive, and it is a cost that rarely appears in anyone's budget.</p>

<p>Establish where construction water comes from before you buy, not after the first slab.</p>

<h2>Storage</h2>

<p>Whatever the source, tank capacity is what actually makes a hill house comfortable. Enough storage rides out a dry week, a pump failure, or a tanker that does not come.</p>

<p>Ask what any built property has, and if you are building, be generous with it. It is the cheapest insurance on the plot.</p>

<h2>Electricity</h2>

<h3>Is it available?</h3>
<p>Electricity reaches most inhabited parts of Morni. The question is not whether it exists but how far the nearest pole is from your plot, because bringing a connection in is at your cost and the distance decides the number.</p>

<p>Ask for the distance in metres, and get it confirmed rather than estimated.</p>

<h3>How reliable is it?</h3>
<p>Cuts are longer here than in Panchkula, especially during and after storms. Any house you intend to use should have backup, and any stay business must have it.</p>

<h3>What to check on a built property</h3>
<ul class="chk">
  <li>Is there an inverter or generator, and what does it actually run?</li>
  <li>How old is the battery bank?</li>
  <li>Does the backup cover the water pump? &mdash; the one people forget</li>
  <li>Is the wiring done for hill damp, or is it plains work?</li>
</ul>

<p>That third point is the important one. No power means no pump, which means no water in the tank, which is how a house with both a borewell and an inverter still runs dry.</p>

<h2>Solar</h2>

<p>Sun is one thing Morni has in quantity for most of the year, and solar water heating in particular pays for itself in a hill winter. Solar power for lighting and a pump is increasingly common here too.</p>

<p>Worth asking about on any built property, and worth planning for on any plot &mdash; particularly which way the roof will face.</p>

<h2>The questions, in one list</h2>

<ul class="chk">
  <li>Which of the three sources is this &mdash; line, borewell or channel?</li>
  <li>If a line: how far is the connection point?</li>
  <li>If a borewell: what depth, and does the yield hold in May?</li>
  <li>If a channel: which months does it actually run?</li>
  <li>What is the storage capacity?</li>
  <li>Where will construction water come from?</li>
  <li>How far is the nearest electricity pole?</li>
  <li>What backup exists, and does it run the pump?</li>
  <li>What do the neighbours do in summer?</li>
</ul>

<p>Nine questions. Ask them before the price is discussed, and you will avoid the most common regret in these hills.</p>

