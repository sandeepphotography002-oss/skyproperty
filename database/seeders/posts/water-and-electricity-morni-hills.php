<p>Ask about water on a Morni plot and you will usually be told "water is there". It is not a lie. It is just three different answers wearing the same words, and the difference between them decides whether you can live on the land.</p>

<h2>The three water sources, honestly</h2>

<h3>1. Village water line — the best answer</h3>
<p>A piped supply from the village scheme. Reliable through most of the year, though pressure drops in May when everybody is drawing.</p>
<p>Ask: is the line at the boundary or two hundred metres away? Bringing it in is at your cost, and on a hill that cost is not small.</p>

<h3>2. Borewell — good, with a question attached</h3>
<p>Groundwater in these hills sits at very different depths pocket to pocket. A borewell fifty metres away might be at 200 feet; yours might need 400.</p>
<p>Ask: what depth did the neighbours drill to, and does the yield hold in May? A borewell that runs in September and struggles in June is only half a supply.</p>

<h3>3. Seasonal channel — not a water supply for a house</h3>
<p>Most terraced land here has a natural channel that carries water from about July into October and is dry the rest of the year.</p>
<p>It is genuinely useful for an orchard or for field crops. It is not water for a house, and describing it as "water is there" while showing you the plot in August is how people end up with tankers.</p>

