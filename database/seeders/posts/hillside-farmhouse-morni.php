  <li>Cut the platform, and let it stand through a wet spell if the timetable allows.</li>
  <li>Build retaining structures with proper drainage behind them.</li>
  <li>Then foundations, then the house.</li>
  <li>Take roof water well away from the structure, not to its base.</li>
  <li>Watch the first monsoon closely and correct anything immediately.</li>
</ol>

<p>Reversing steps two and four is the most common and most expensive error on hill sites.</p>

