<h2>Retaining walls, in plain terms</h2>

<p>These are the most expensive element of a hill build and the one buyers understand least. A few principles are worth knowing before you talk to a builder.</p>

<ul>
  <li><strong>A retaining wall holds back earth, not water.</strong> Water behind it is what destroys it, which is why drainage is part of the wall and not an extra.</li>
  <li><strong>Weep holes matter.</strong> A wall with no way for water to escape is a wall waiting to fail.</li>
  <li><strong>Height increases cost disproportionately.</strong> Two low walls in steps are often cheaper and safer than one tall one.</li>
  <li><strong>Fill is weaker than cut.</strong> Building on made up ground needs more care than building on original slope.</li>
  <li><strong>Cracks are information.</strong> Fine hairline cracks are common; anything wider, or a bulge, needs looking at properly.</li>
</ul>

<p>When you inspect an existing house, walk the outside of every retaining wall and look for damp patches, bulges and fresh plaster over old repairs.</p>

<h2>A sensible build sequence on a slope</h2>

<ol>
