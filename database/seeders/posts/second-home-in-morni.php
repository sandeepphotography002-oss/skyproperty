<h2>Choosing the site</h2>

<h3>Access</h3>

<p>Can a car reach the gate in the monsoon? If the last stretch is a walk, you will use the house less than you think, and building it will cost more.</p>

<h3>Slope</h3>

<p>Gentle slope means one retaining wall. A steep cut face means three, plus drainage above the house. This is where build budgets are lost.</p>

<h3>Water</h3>

<p>Ask where it comes from and see it in the dry months. A channel that is full in September proves nothing about May.</p>

<h3>Neighbours</h3>

<p>A house with people living nearby is looked after by more than your caretaker. Complete isolation sounds romantic in April and feels different in August.</p>

