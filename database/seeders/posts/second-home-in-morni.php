<h2>Furnishing for a house you visit sometimes</h2>

<p>A hill house left closed for weeks is a different problem from a city flat. What survives here is simple, and what suffers is anything soft or delicate.</p>

<ul>
  <li>Keep textiles minimal, or store them in sealed boxes between visits.</li>
  <li>Choose furniture that tolerates damp. Solid wood and metal over particle board.</li>
  <li>Fit good locks and shutters, and leave nothing valuable behind.</li>
  <li>Keep a basic tool kit, a spare pump part and a torch on site.</li>
  <li>Leave the water system in a state a caretaker can restart without you.</li>
</ul>

