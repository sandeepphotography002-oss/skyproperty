<h2>Being realistic about the season</h2>

<p>Demand runs roughly March to June and again in October, concentrated at weekends, and comes largely from Chandigarh, Panchkula and Mohali. Monsoon months are quiet and the roads are harder.</p>

<p>A workable plan accepts that a limited number of good weekends must carry the year, and keeps fixed costs low enough that the quiet months are survivable.</p>

<h2>Setting your room rate</h2>

<p>New owners usually price by guessing what sounds reasonable. In a seasonal market that is expensive, because the few good weekends have to carry the year.</p>

<ol>
  <li>Look at what comparable rooms in your part of Morni charge on a Saturday in April, not on a Tuesday in August.</li>
  <li>Set your in season weekend rate first. That is the rate that matters.</li>
  <li>Set a weekday rate below it, and an off season rate below that.</li>
  <li>Decide whether meals are included, because it changes the comparison a guest makes.</li>
  <li>Account for platform commission before you decide the number is enough.</li>
</ol>

<p>Discounting the peak weekends to fill the quiet ones is the classic error. The quiet weeks will be quiet regardless, and you will have given away the margin that funds the year.</p>

