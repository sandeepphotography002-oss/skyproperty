<h2>If you are buying a running homestay</h2>

<h3>Read the numbers properly</h3>

<ol>
  <li><strong>Ask for occupancy month by month, for two years.</strong> An annual average hides everything that matters in a seasonal market.</li>
  <li><strong>Ask for average room rate by month too.</strong> High occupancy at a low rate is a different business.</li>
  <li><strong>Ask what is included.</strong> Meals, transport and activities change both revenue and cost.</li>
  <li><strong>Ask about platform commission.</strong> Bookings that arrive through platforms cost a share of every night.</li>
  <li><strong>Ask what staff cost across the full year</strong>, not just in season.</li>
</ol>

<h3>Check the licence position</h3>

<ul>
  <li>Is it registered under the state homestay scheme, and is the registration current?</li>
  <li>Do the registration and any other permissions transfer with the sale, or must you reapply?</li>
  <li>Are there local requirements you would inherit?</li>
</ul>

<h3>Check what actually transfers</h3>

