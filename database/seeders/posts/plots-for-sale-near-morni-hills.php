<h2>Approved colony plots</h2>

<p>The safest and the dearest. What matters is verifying the approval rather than accepting a brochure.</p>

<ul>
  <li>Ask which authority sanctioned the layout and get the reference.</li>
  <li>Verify it independently rather than from the developer's paperwork alone.</li>
  <li>Check what services are actually laid, not what is promised.</li>
  <li>Ask what proportion of the colony is built and occupied.</li>
  <li>Check maintenance arrangements and any recurring charges.</li>
</ul>

<h2>Village abadi plots</h2>

<p>Inside the settled part of a village. Usually level, usually near existing water and power, and a well trodden path for building a house.</p>

<ul>
  <li>Boundaries are tight; know exactly what your neighbour may build against.</li>
  <li>Lane width limits construction vehicles.</li>
  <li>Ask whether the lane is public or land used by custom.</li>
  <li>Count owner names on the fard — inheritance is common here too.</li>
</ul>

<h2>Plots carved from open land</h2>

<p>The cheapest and the one that needs the most care. Somebody is selling you part of an agricultural holding as a plot.</p>

<ol>
  <li>Establish the classification before anything else. This is the whole question.</li>
  <li>Establish how the portion is defined on the ground and in the deed.</li>
  <li>Establish recorded access to the plot, not access by goodwill.</li>
  <li>Ask whether services can be brought, and at whose cost.</li>
  <li>Ask whether the split will appear properly in the record.</li>
  <li>Price it as agricultural land unless and until the position is settled.</li>
</ol>

<p>These plots are not a trap in themselves. Many are perfectly good buys. They become a trap when they are priced as though building permission is certain.</p>

<h2>Questions that apply to all three</h2>

<ul>
  <li>Is any acquisition or road widening notified nearby?</li>
