<h2>What services actually cost to bring</h2>

<p>On an approved plot, water, power and a road are usually laid or promised. On a village plot they are close by. On land carved from a field, they are your problem, and buyers routinely leave them out of the budget.</p>

<ul>
  <li><strong>Electricity.</strong> Cost rises with distance from the nearest pole. Ask how far, and whether poles must be added.</li>
  <li><strong>Water.</strong> A borewell is a known cost with an unknown outcome. Ask what neighbours had to spend and to what depth.</li>
  <li><strong>Approach.</strong> Turning a field edge into something a car can use is real construction, not landscaping.</li>
  <li><strong>Drainage.</strong> On level ground, where water leaves your plot matters as much as where it arrives.</li>
  <li><strong>Boundary.</strong> Marking is essential; walling is optional and considerably dearer.</li>
</ul>

<p>Get rough numbers for all five before comparing a cheap open land plot with a dearer approved one. The gap frequently closes.</p>

