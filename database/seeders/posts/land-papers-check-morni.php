<h2>If something is wrong</h2>

<p>A missing mutation, a boundary that does not match, an unrecorded co-owner — none of these has to end the deal. They just have to be fixed <em>before</em> money changes hands, by the seller, at the seller's cost.</p>

<p>What must not happen is paying now on a promise to sort it out later. Once the money has moved, the incentive to fix anything moves with it.</p>

