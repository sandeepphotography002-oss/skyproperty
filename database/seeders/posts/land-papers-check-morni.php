<h2>Warning signs</h2>

<p>None of these means fraud. Each means slow down and ask more.</p>

<ul>
  <li><strong>Reluctance to share the khasra number.</strong> It is not secret. Hesitation here is worth noticing.</li>
  <li><strong>"Mutation is in process."</strong> Ask when it was applied for and to see the receipt. Often the answer is that nothing was filed.</li>
  <li><strong>Pressure to pay a token today.</strong> Nothing in Morni is so scarce that it cannot wait a week.</li>
  <li><strong>An owner who is never available.</strong> If everything comes through a middleman and the owner is always out of station, wait until you meet them.</li>
  <li><strong>A boundary described but not walked.</strong> Every corner should be shown on the ground.</li>
