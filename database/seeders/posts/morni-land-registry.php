<h2>The step after registry</h2>

<p>Apply for mutation. This updates the revenue record so that the jamabandi shows your name against the khasra. Without it:</p>

<ul>
  <li>The record still shows the seller as owner.</li>
  <li>A future buyer will pull the record and find a mismatch.</li>
  <li>Anything requiring proof of ownership becomes harder than it should be.</li>
</ul>

<p>Do it promptly, keep the mutation order with the registered deed, and pull a fresh jamabandi afterwards to confirm the change appears.</p>

