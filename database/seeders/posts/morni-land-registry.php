<h2>What registry is, and what it is not</h2>

<p>Registration records the sale deed with the state. It is the legal transfer of the property from seller to buyer.</p>

<p>It is <strong>not</strong> the same as mutation. Mutation is the separate step that updates the revenue record — the jamabandi — to show your name. Until mutation is done, the record that everyone consults still shows the seller. This distinction causes more confusion than any other part of the process.</p>

