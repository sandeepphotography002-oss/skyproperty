<h3>Pinjore</h3>

<p>Pinjore is best known for its historic terraced gardens, which are a considerable detour in scale and a short one in distance. It sits on the road towards Kalka and is easy to fit in on the way back rather than on the way up, when you want to reach the lakes early.</p>

<p>The area also has a well known temple complex. Check current timings and any entry arrangements before you plan around them.</p>

<h3>Kalka</h3>

<p>A town on the highway towards Shimla, and the starting point of the narrow gauge hill railway to Shimla. Worth a stop if trains interest you or if you are heading further into Himachal afterwards.</p>

<h2>In Morni itself</h2>

<h3>Morni village</h3>

<p>The market, shops and ordinary hill life below the lakes. Better for food than the lakes, and the most reliable place to ask directions from someone who knows.</p>

<h3>The fort</h3>

<p>There is an old fort at Morni that visitors go to. Ask locally about current access before making a plan around it.</p>

