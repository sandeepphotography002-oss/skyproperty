<h2>What a plot costs before you build on it</h2>

<p>Buyers often assume that land, unlike a house, costs nothing to own. Mostly true, but not entirely, and the gap surprises people who buy and then wait five years.</p>

<ul>
  <li><strong>Boundary marking and re-marking.</strong> Stones move, bunds erode, and an unmarked boundary is an argument waiting to happen.</li>
  <li><strong>Clearing.</strong> Growth here is fast. A plot left completely alone becomes impassable within a couple of seasons.</li>
  <li><strong>Keeping the record current.</strong> Mutation done, a fresh fard on file, and any change in family circumstances reflected.</li>
