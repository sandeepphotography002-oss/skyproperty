<h2>1. Undivided inherited ownership</h2>

<p><strong>What it looks like:</strong> the record shows one name, or several, and the seller says the family has agreed. Nobody has formally divided anything.</p>

<p><strong>What it costs late:</strong> the registry cannot proceed without every co-owner. One brother abroad, one unwilling, and the sale waits months or dies.</p>

<p><strong>Check early:</strong> pull the fard and count the names. Ask who else has a claim by inheritance, in writing.</p>

<h2>2. Access that is not yours</h2>

<p><strong>What it looks like:</strong> a track to the plot across a neighbour field, working today because everyone gets on.</p>

<p><strong>What it costs late:</strong> the neighbour sells, the new owner closes the track, and your plot is landlocked.</p>

<p><strong>Check early:</strong> ask what right of way exists on record. Verbal permission is not access.</p>

<h2>3. Record area not matching the ground</h2>

<p><strong>What it looks like:</strong> the seller quotes four kanal, the fard says three and a half.</p>

<p><strong>What it costs late:</strong> you pay for land you do not receive, and a boundary dispute with a neighbour who has been cultivating the difference for years.</p>

<p><strong>Check early:</strong> match the area on record to the quote before discussing price, and walk the boundary with the seller and a neighbour present.</p>

<h2>4. Assuming you can build</h2>

<p><strong>What it looks like:</strong> agricultural land, a seller who says conversion is a formality, and a buyer who believes it.</p>

<p><strong>What it costs late:</strong> you own land you cannot build on, and the resale market for it is smaller than the one you bought into.</p>

<p><strong>Check early:</strong> confirm classification and permitted use with the district office, before a token is paid.</p>

<h2>5. Water that exists only in September</h2>

<p><strong>What it looks like:</strong> a channel running full, an assurance that water is never a problem.</p>

<p><strong>What it costs late:</strong> a house or a guest operation without water in May and June, which is exactly when you want to be there.</p>

<p><strong>Check early:</strong> visit in the dry months. Ask the neighbours, not the seller, where their water comes from.</p>

<h2>6. The last kilometre</h2>

<p><strong>What it looks like:</strong> a fine road that becomes something else for the final stretch.</p>

<p><strong>What it costs late:</strong> materials arrive by tractor or on heads, and the same house costs materially more to build.</p>

<p><strong>Check early:</strong> ask whether a cement truck can reach the boundary. Drive the last stretch yourself, ideally after rain.</p>

<h2>7. Slope you have not costed</h2>

<p><strong>What it looks like:</strong> a beautiful plot on a steep face, cheaper per unit than the flatter one nearby.</p>

<p><strong>What it costs late:</strong> retaining walls, drainage above the house and a foundation that consumes the saving several times over.</p>

<p><strong>Check early:</strong> get a local builder to look before you buy, not after.</p>

<h2>8. Skipping mutation after registry</h2>

<p><strong>What it looks like:</strong> registry done, deed in hand, everyone relaxed.</p>

<p><strong>What it costs late:</strong> the revenue record still shows the seller, and the problem surfaces years later when you sell or seek a loan.</p>

<p><strong>Check early:</strong> apply for mutation promptly and pull a fresh fard afterwards to confirm your name appears.</p>

