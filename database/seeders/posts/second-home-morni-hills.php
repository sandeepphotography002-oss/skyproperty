<p>There is a lesson available locally here. Much of the land in Morni is difficult to sell precisely because it was inherited by several people and never formally divided. The problem you would be creating for your own children is the same one you encounter as a buyer.</p>

<h2>What to write down at the start</h2>

<ol>
  <li><strong>Who contributed what.</strong> Record it, even among siblings, especially among siblings.</li>
  <li><strong>Who pays the running costs.</strong> Caretaker, repairs and monsoon work happen whether or not anyone visited.</li>
  <li><strong>How use is shared.</strong> An informal understanding works until two families want the same weekend.</li>
  <li><strong>What happens if one person wants out.</strong> Agree the principle now; it costs nothing while everyone is content.</li>
  <li><strong>Who holds the papers</strong>, and who else knows where they are.</li>
  <li><strong>Who decides on repairs</strong> above a certain amount.</li>
</ol>

<p>None of this needs to be adversarial. A page of agreed notes, kept with the deed, prevents nearly every dispute we have seen over hill property.</p>

<h2>Succession, plainly</h2>

<ul>
  <li>Property left without clear succession becomes exactly the kind of undivided holding that takes years to sell.</li>
  <li>A will removes most of that difficulty. Take proper advice on how to do it.</li>
  <li>Tell your family where the papers are. A great deal of difficult land in this district is difficult because the person who understood it is gone.</li>
  <li>Keep mutation current after any change, so the record reflects reality.</li>
</ul>

<h2>The paper file to keep</h2>

<ul>
  <li>Registered sale deed</li>
  <li>Mutation order and a recent fard showing the current owner</li>
  <li>Khasra number and village map extract</li>
  <li>Payment records for the purchase, including the token</li>
  <li>Any right of way or access document</li>
  <li>Correspondence confirming classification</li>
  <li>Building papers, borewell details, electricity connection in whose name</li>
  <li>Caretaker arrangement and contact details</li>
  <li>Dated boundary photographs from each visit</li>
</ul>

<p>Handing this file to a buyer one day is worth real money. Handing it to your family is worth more.</p>

<h2>Shared use, in practice</h2>

<ul>
  <li>Agree a simple booking method, however informal — a message group is enough.</li>
  <li>Agree who is responsible for leaving the house ready for the next person.</li>
  <li>Agree a common fund for running costs rather than settling up each time.</li>
  <li>Keep one person as the point of contact for the caretaker.</li>
  <li>Review it once a year, when circumstances have changed and nobody has said so.</li>
</ul>

<h2>The lesson this district teaches</h2>

<p>Spend a few weeks looking at land in Morni and you meet the same obstacle repeatedly: a holding that four or five people have a claim to, where nobody disagrees but nobody can act, and where a sale takes years or never happens.</p>

<p>Almost none of that was intended. It is what happens when property passes down two or three generations without anyone writing anything down.</p>

<ul>
  <li>The original owner meant to sort it out and did not.</li>
  <li>The next generation used it happily and saw no reason to formalise anything.</li>
  <li>By the third generation, several people live in different cities and one is unreachable.</li>
  <li>The land is now worth less than comparable land with clean title.</li>
</ul>

<p>The buyer who complains about this while creating exactly the same situation for their own children is a common figure. Half an hour with an advocate at the time of purchase prevents it entirely.</p>

<h2>A short annual habit</h2>

<ol>
  <li>Pull a fresh fard once a year and confirm the record still reads as it should.</li>
  <li>Visit and photograph the boundary, dated.</li>
  <li>Check markers are in place.</li>
  <li>Update the paper file with anything that changed.</li>
  <li>Tell whoever in the family would need to find it where it is kept.</li>
</ol>

<p>Twenty minutes a year, and it is the difference between a property your family can deal with easily and one they cannot.</p>

