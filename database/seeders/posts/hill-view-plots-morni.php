<h2>Why some views disappear</h2>

<ul>
  <li><strong>Somebody builds in front.</strong> The most common, and the most checkable.</li>
  <li><strong>Trees grow.</strong> Slower, quieter, and entirely predictable if you look.</li>
  <li><strong>You build lower than you thought.</strong> Cutting into a slope can drop the house below the sight line.</li>
  <li><strong>A boundary wall goes up.</strong> Yours or a neighbour's.</li>
  <li><strong>A road or line is put in.</strong> Rare here, but worth asking.</li>
</ul>

<h2>The five checks</h2>

<h3>1. Map what is between you and the view</h3>

<p>Stand at the house position and identify every parcel of land in the sight line down to where the ground drops away. For each one, ask who owns it.</p>

<h3>2. Establish whether those parcels are buildable</h3>

<p>Classification decides this and it is checkable at the district office. Agricultural land where building is not permitted is far more likely to stay open than land already classified for it.</p>

<h3>3. Read the slope in front</h3>

<table>
  <thead>
