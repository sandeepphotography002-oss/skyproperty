<h2>Buying the protection, where it is available</h2>

<p>The only genuine way to keep a view is to control the land it crosses. That is not always possible, but it is worth asking about at the time of the original purchase rather than after somebody starts building.</p>

<ul>
  <li><strong>Is the parcel in front small and affordable?</strong> Sometimes a strip of land is far cheaper than the view premium you already paid.</li>
  <li><strong>Would the seller include it?</strong> If it is part of the same holding, ask. Sellers often agree at the time and rarely afterwards.</li>
  <li><strong>Can you take a recorded agreement instead?</strong> Take advice on what is enforceable rather than relying on an understanding.</li>
  <li><strong>Is it worth simply moving the house up?</strong> A few metres of height can clear an obstruction that money cannot.</li>
</ul>

