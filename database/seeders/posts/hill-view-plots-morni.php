</table>

<h3>4. Look at the trees, not just the buildings</h3>

<p>Young plantations and self seeded growth below a plot will close a view within a decade. Look down the slope and estimate the height of what is growing there. Mature trees are stable; saplings are a future wall.</p>

<h3>5. Check what has been built nearby in three years</h3>

<p>Count new roofs within sight. If three houses have gone up recently, more will. If nothing has been built in a decade, that tells you something about access and classification in that pocket.</p>

