<h2>Why two plots the same size cost different money</h2>

<p>This is the question we are asked most, and the honest answer is that the view has very little to do with it. Almost everything in Morni has a view.</p>

<h3>The approach road</h3>
<p>The single biggest factor. A road-touch plot commands a large premium because building material has to reach the site. If a tractor cannot get there, sand, cement and steel go up by head-load, and the construction cost can rise by a third or more.</p>
<p>Walk the approach yourself, all the way in, and ask what it looks like in July.</p>

<h3>Level ground versus a cut face</h3>
<p>A gentle slope needs one retaining wall. A steep cut may need three, plus deeper foundations. That is lakhs of difference on the same "plot area", before a single wall of the house goes up.</p>

<h3>Water</h3>
<p>Three possibilities, in descending order of value: a village water line, a working borewell, and a seasonal channel. The third one is dry from about January to June. Ask which, and do not accept "water is there" as an answer.</p>

<h3>Classification</h3>
<p>A residential plot can be built on. Agricultural land cannot, without a change of land use. That difference alone accounts for a large part of the price gap between two neighbouring pieces of land.</p>

<h3>How far off the Morni road</h3>
<p>Every kilometre inward lowers the rate and raises what you will spend reaching it, in fuel, in time and in what a contractor charges to work there.</p>

