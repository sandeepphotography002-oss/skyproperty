<h2>Before you get out of the car</h2>

<ul>
  <li>How did the last five hundred metres feel? That is your construction road.</li>
  <li>Is there room to turn a vehicle near the plot?</li>
  <li>Where does the road drain when it rains? Downhill onto this land, or away from it?</li>
