<h2>Look up before you look out</h2>

<p>Everyone arrives and looks at the view. Look uphill first.</p>

<ul>
  <li><strong>What is above the plot?</strong> Water from a hundred metres above will arrive on your land in August whether you planned for it or not.</li>
  <li><strong>Is there a cut face or loose bank?</strong> Ask what has come down in past monsoons.</li>
  <li><strong>Is there cultivation above?</strong> Irrigation upslope changes how wet your ground stays.</li>
</ul>

<h2>Then walk the boundary</h2>

<ol>
  <li>Walk all four sides with the seller present.</li>
  <li>Ask a neighbour to confirm the line, not just the seller.</li>
  <li>Note any wall, bund or tree line used as a marker, and whether it looks recent.</li>
  <li>Look for signs of cultivation crossing the boundary — this is where disputes start.</li>
  <li>Match what you walked to the area on the fard.</li>
</ol>

